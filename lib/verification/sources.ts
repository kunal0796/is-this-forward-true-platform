const SOURCE_INDEX = new Map(TRUSTED_SOURCES.map((s) => [s.id, s]))

export function getSource(id: string): Source | undefined {
  return SOURCE_INDEX.get(id)
}

export function findSourceByHostname(hostname: string): Source | undefined {
  const host = hostname.toLowerCase().replace(/^www\./, '')
  return TRUSTED_SOURCES.find((s) => host === s.domain || host.endsWith(`.${s.domain}`))
}

